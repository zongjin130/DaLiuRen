def get_gan_index(gan: str) -> int:
    """获取天干索引（0-9）"""
    return TIAN_GAN.index(gan)


def get_zhi_index(zhi: str) -> int:
    """获取地支索引（0-11）"""
    return DI_ZHI.index(zhi)


def get_wuxing(element: str) -> str:
    """获取天干或地支的五行"""
    if element in GAN_WUXING:
        return GAN_WUXING[element]
    return ZHI_WUXING[element]


def is_sheng(a: str, b: str) -> bool:
    """判断a是否生b"""
    return WUXING_SHENG.get(get_wuxing(a)) == get_wuxing(b)


def is_ke(a: str, b: str) -> bool:
    """判断a是否克b"""
    return WUXING_KE.get(get_wuxing(a)) == get_wuxing(b)


def get_sheng(a: str) -> str:
    """获取a所生的五行"""
    return WUXING_SHENG[get_wuxing(a)]


def get_ke(a: str) -> str:
    """获取a所克的五行"""
    return WUXING_KE[get_wuxing(a)]


def is_he(a: str, b: str) -> bool:
    """判断a和b是否六合"""
    return LIU_HE.get(a) == b


def is_chong(a: str, b: str) -> bool:
    """判断a和b是否六冲"""
    return LIU_CHONG.get(a) == b


def get_chong(zhi: str) -> str:
    """获取地支的冲"""
    return LIU_CHONG[zhi]


def gan_to_ganzhi(gan_index: int, zhi_index: int) -> str:
    """天干索引+地支索引 -> 干支字符串"""
    return TIAN_GAN[gan_index % 10] + DI_ZHI[zhi_index % 12]
